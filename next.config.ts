import type { NextConfig } from "next";

// Security response headers (added to close ghaudit web-missing-* findings).
// The CSP intentionally allows 'unsafe-inline'/'unsafe-eval' because Next.js
// injects inline hydration scripts and styled content; a strict nonce-based
// policy would require middleware and is a follow-up. Even permissive, having
// a CSP plus the framing/sniffing/referrer headers is a meaningful hardening
// baseline over having none.
const securityHeaders = [
  {
    key: "Content-Security-Policy",
    value: [
      "default-src 'self'",
      "script-src 'self' 'unsafe-inline' 'unsafe-eval'",
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data: blob:",
      "font-src 'self' data:",
      "connect-src 'self'",
      "frame-ancestors 'none'",
      "base-uri 'self'",
      "form-action 'self'",
      "object-src 'none'",
    ].join("; "),
  },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
];

const nextConfig: NextConfig = {
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
